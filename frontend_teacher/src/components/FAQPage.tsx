"use client";

import { useState } from "react";
import { ChevronDown, Search, HelpCircle, Book, Laptop, UserCheck } from "lucide-react";
import { motion, AnimatePresence } from "framer-motion";

const categories = [
    { id: 'general', name: 'General', icon: HelpCircle },
    { id: 'academic', name: 'Academic', icon: Book },
    { id: 'technical', name: 'Technical', icon: Laptop },
    { id: 'account', name: 'Account', icon: UserCheck },
];

const detailedFaqs = [
    {
        category: 'general',
        question: "What is Prayukti?",
        answer: "Prayukti is the official Virtual Laboratory Ecosystem of MMMUT Gorakhpur. It provides high-fidelity simulations of engineering experiments, allowing students to practice and master concepts remotely."
    },
    {
        category: 'academic',
        question: "Is the simulation data valid for lab reports?",
        answer: "Yes, the data generated by Prayukti simulations is based on real-world physics and mathematical models approved by the university faculty. You can use these results for your preparatory lab reports."
    },
    {
        category: 'technical',
        question: "Supported browsers?",
        answer: "Prayukti works best on latest versions of Chrome, Firefox, Edge, and Safari. We recommend using a desktop browser for the best experience with interactive simulations."
    },
    {
        category: 'account',
        question: "How to register?",
        answer: "Registration is exclusive to MMMUT students. Use your official @mmmut.ac.in email address on the registration page to create your account."
    },
    // Add more...
];

export default function FAQPage() {
    const [activeCategory, setActiveCategory] = useState('general');
    const [openIndex, setOpenIndex] = useState<number | null>(null);

    const filteredFaqs = detailedFaqs.filter(f => f.category === activeCategory);

    return (
        <div className="min-h-screen flex flex-col bg-slate-50 dark:bg-slate-950">
            <main className="flex-1 pt-32 pb-24">
                <div className="container mx-auto px-4 max-w-6xl">
                    <header className="text-center mb-16 space-y-4">
                        <h1 className="text-5xl md:text-7xl font-black text-primary dark:text-white tracking-tighter uppercase leading-none">
                            Knowledge <span className="text-accent">Base</span>
                        </h1>
                        <p className="text-slate-500 font-bold uppercase tracking-widest text-xs">
                            Find detailed answers to all your questions about the Prayukti platform.
                        </p>
                    </header>

                    <div className="grid grid-cols-1 lg:grid-cols-4 gap-12">
                        {/* Sidebar Categories */}
                        <div className="space-y-2">
                            {categories.map((cat) => (
                                <button
                                    key={cat.id}
                                    onClick={() => {
                                        setActiveCategory(cat.id);
                                        setOpenIndex(null);
                                    }}
                                    className={`w-full flex items-center gap-4 px-6 py-4 rounded-2xl font-black uppercase tracking-widest text-[10px]  border-2 ${
                                        activeCategory === cat.id 
                                        ? 'bg-primary text-white border-primary  /20' 
                                        : 'bg-white dark:bg-slate-900 text-slate-400 border-slate-100 dark:border-slate-800 hover:border-accent hover:text-accent'
                                    }`}
                                >
                                    <cat.icon size={18} />
                                    {cat.name}
                                </button>
                            ))}
                        </div>

                        {/* FAQ List */}
                        <div className="lg:col-span-3 space-y-4">
                            <AnimatePresence mode="wait">
                                <motion.div
                                    key={activeCategory}
                                    initial={{ opacity: 0, x: 20 }}
                                    animate={{ opacity: 1, x: 0 }}
                                    exit={{ opacity: 0, x: -20 }}
                                    className="space-y-4"
                                >
                                    {filteredFaqs.map((faq, index) => (
                                        <div key={index} className="bg-white dark:bg-slate-900 rounded-[2rem] border-2 border-slate-100 dark:border-slate-800 overflow-hidden  hover:border-accent/50 group">
                                            <button
                                                onClick={() => setOpenIndex(openIndex === index ? null : index)}
                                                className="w-full flex items-center p-8 text-left"
                                            >
                                                <span className="flex-shrink-0 mr-6">
                                                    <div className={`w-10 h-10 rounded-xl flex items-center justify-center transition-colors ${openIndex === index ? 'bg-accent text-white' : 'bg-slate-50 dark:bg-slate-800 text-slate-400'}`}>
                                                        <ChevronDown className={`w-5 h-5  duration-300 ${openIndex === index ? 'rotate-180' : ''}`} />
                                                    </div>
                                                </span>
                                                <span className="text-xl font-black text-primary dark:text-white uppercase tracking-tight">{faq.question}</span>
                                            </button>
                                            
                                            <AnimatePresence>
                                                {openIndex === index && (
                                                    <motion.div
                                                        initial={{ height: 0, opacity: 0 }}
                                                        animate={{ height: 'auto', opacity: 1 }}
                                                        exit={{ height: 0, opacity: 0 }}
                                                        className="overflow-hidden"
                                                    >
                                                        <div className="px-24 pb-10 text-slate-500 dark:text-slate-400 font-medium leading-relaxed">
                                                            {faq.answer}
                                                        </div>
                                                    </motion.div>
                                                )}
                                            </AnimatePresence>
                                        </div>
                                    ))}
                                </motion.div>
                            </AnimatePresence>
                        </div>
                    </div>
                </div>
            </main>
        </div>
    );
}
